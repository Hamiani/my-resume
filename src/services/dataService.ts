export const getExperiences = (language: LanguageType): ExperienceType[] => {
  return experiencesEN.map((exp, index) => {
    const frExp = experiencesFR[index];

    return {
      id: exp.id,
      title: {
        fr: frExp.post,
        en: exp.position,
      },
      company: exp.company,
      client: exp.client,
      period: {
        fr: frExp.period,
        en: exp.period,
      },
      location: {
        fr: frExp.location,
        en: exp.location,
      },
      context: {
        fr: frExp.context,
        en: exp.context,
      },
      responsibilities: {
        fr: frExp.responsibilities,
        en: exp.responsibilities,
      },
      technical_environment: exp.technical_environment,
      description: {
        fr:
          frExp.context.substring(0, 150) +
          (frExp.context.length > 150 ? "..." : ""),
        en:
          exp.context.substring(0, 150) +
          (exp.context.length > 150 ? "..." : ""),
      },
    };
  });
};

export default getExperiences;
